function fail(messages) {
  const errors = Array.isArray(messages) ? messages : [messages];
  throw new Error(
    `Structured block registration validation failed:\n\n${errors.map((message) => `- ${message}`).join("\n")}`,
  );
}

function duplicates(values) {
  const seen = new Set();
  const repeated = new Set();
  for (const value of values) {
    if (seen.has(value)) repeated.add(value);
    seen.add(value);
  }
  return [...repeated];
}

function assertAttributeDefault(blockName, attributeName, schema, errors) {
  if (!("default" in schema)) return;
  const value = schema.default;
  const valid =
    (schema.type === "array" && Array.isArray(value)) ||
    (schema.type === "boolean" && typeof value === "boolean") ||
    (schema.type === "number" && typeof value === "number" && Number.isFinite(value)) ||
    (schema.type === "object" &&
      value !== null &&
      typeof value === "object" &&
      !Array.isArray(value)) ||
    (schema.type === "string" && typeof value === "string");
  if (!valid) errors.push(`${blockName} attribute ${attributeName} has an incompatible default`);
}

function assertAttributeSchema(blockName, attributeName, schema, errors, allowedTypes) {
  if (!schema || !allowedTypes.has(schema.type)) {
    errors.push(`${blockName} attribute ${attributeName} has an invalid type`);
    return;
  }

  assertAttributeDefault(blockName, attributeName, schema, errors);

  if (schema.enum !== undefined) {
    if (
      !Array.isArray(schema.enum) ||
      schema.enum.length === 0 ||
      schema.enum.some((value) => typeof value !== "string")
    ) {
      errors.push(`${blockName} attribute ${attributeName} has an invalid enum`);
    }
    if (schema.type !== "string") {
      errors.push(`${blockName} attribute ${attributeName} enum must be for a string`);
    } else if (
      "default" in schema &&
      schema.default !== "" &&
      typeof schema.default === "string" &&
      !schema.enum.includes(schema.default)
    ) {
      errors.push(`${blockName} attribute ${attributeName} default is not in its enum`);
    }
  }

  if (schema.legacyReads !== undefined) {
    if (
      !Array.isArray(schema.legacyReads) ||
      schema.legacyReads.some((value) => typeof value !== "string" || !value)
    ) {
      errors.push(`${blockName} attribute ${attributeName} has invalid legacy row reads`);
    }
  }

  if (
    schema.ui !== undefined &&
    !["boolean", "json", "media", "number", "select", "text", "textarea", "url"].includes(
      schema.ui?.kind,
    )
  ) {
    errors.push(`${blockName} attribute ${attributeName} has an invalid editor kind`);
  }

  if (schema.properties !== undefined) {
    if (schema.type !== "object") {
      errors.push(`${blockName} attribute ${attributeName} declares properties on a non-object`);
    } else if (
      !schema.properties ||
      typeof schema.properties !== "object" ||
      Array.isArray(schema.properties)
    ) {
      errors.push(`${blockName} attribute ${attributeName}.properties must be an object`);
    } else {
      for (const [propertyName, propertySchema] of Object.entries(schema.properties)) {
        assertAttributeSchema(
          blockName,
          `${attributeName}.properties.${propertyName}`,
          propertySchema,
          errors,
          allowedTypes,
        );
      }
    }
  }
  if (schema.additionalProperties !== undefined && schema.additionalProperties !== false) {
    errors.push(`${blockName} attribute ${attributeName} additionalProperties may only be false`);
  }

  if (schema.items === undefined) return;
  if (schema.type !== "array") {
    errors.push(`${blockName} attribute ${attributeName} declares array items on a non-array`);
    return;
  }

  const itemPath = `${attributeName}.items`;
  if (schema.items?.type === "object" && "properties" in schema.items) {
    const properties = schema.items.properties;
    if (!properties || typeof properties !== "object" || Array.isArray(properties)) {
      errors.push(`${blockName} attribute ${itemPath}.properties must be an object`);
      return;
    }
    const required = schema.items.required ?? [];
    if (
      !Array.isArray(required) ||
      required.some((name) => typeof name !== "string" || !(name in properties))
    ) {
      errors.push(`${blockName} attribute ${itemPath}.required must reference row properties`);
    }
    for (const [fieldName, fieldSchema] of Object.entries(properties)) {
      assertAttributeSchema(
        blockName,
        `${itemPath}.properties.${fieldName}`,
        fieldSchema,
        errors,
        allowedTypes,
      );
    }
    return;
  }

  assertAttributeSchema(blockName, itemPath, schema.items, errors, allowedTypes);
}

export async function loadRegistrations() {
  const files = globSync("*.ts", { cwd: registrationsRoot }).sort();
  if (files.length === 0) fail("No registration files found");

  const registrations = [];
  for (const file of files) {
    const moduleUrl = pathToFileURL(join(registrationsRoot, file));
    const loaded = await import(moduleUrl.href);
    registrations.push({ ...loaded.default, sourceFile: file });
  }
  registrations.sort((a, b) => a.identity.order - b.identity.order);
  return registrations;
}

export function validateRegistrations(registrations) {
  const errors = [];
  const allowedTypes = new Set(["array", "boolean", "number", "object", "string"]);

  for (const key of ["blockName", "catalogId", "order"]) {
    for (const duplicate of duplicates(registrations.map((item) => item.identity[key]))) {
      errors.push(`Duplicate ${key}: ${duplicate}`);
    }
  }
  for (const duplicate of duplicates(registrations.map((item) => item.documentation.path))) {
    errors.push(`Duplicate documentation path: ${duplicate}`);
  }

  for (const registration of registrations) {
    const {
      identity,
      lifecycle,
      container,
      attributes,
      compatibility,
      renderer,
      editor,
      documentation,
      sourceFile,
    } = registration;
    const label = identity?.blockName ?? sourceFile;
    if (identity.blockName !== `getquick/${identity.catalogId}`) {
      errors.push(`${label} must use getquick/<catalogId>`);
    }
    if (sourceFile !== `${identity.catalogId}.ts`) {
      errors.push(`${label} must live in ${identity.catalogId}.ts`);
    }
    if (!Number.isInteger(identity.schemaVersion) || identity.schemaVersion < 1) {
      errors.push(`${label} has an invalid schemaVersion`);
    }
    if (!Number.isInteger(identity.order) || identity.order < 1) {
      errors.push(`${label} has an invalid order`);
    }
    if (lifecycle.status !== "active" && lifecycle.status !== "legacy") {
      errors.push(`${label} has an invalid lifecycle status`);
    }
    if (typeof lifecycle.inserter !== "boolean") {
      errors.push(`${label} must declare inserter visibility`);
    }
    if (lifecycle.status === "legacy" && lifecycle.inserter) {
      errors.push(`${label} is legacy but remains visible in the inserter`);
    }
    if (container !== undefined && typeof container !== "boolean") {
      errors.push(`${label} has an invalid container flag`);
    }
    if (editor.bespoke !== undefined && editor.bespoke !== true) {
      errors.push(`${label} has an invalid bespoke flag`);
    }
    if (container && !editor.bespoke) {
      errors.push(`${label} is a container and needs a bespoke editor rendering InnerBlocks`);
    }
    if (!attributes || Object.keys(attributes).length === 0) {
      errors.push(`${label} has no canonical attributes`);
    }
    for (const [attributeName, schema] of Object.entries(attributes ?? {})) {
      assertAttributeSchema(label, attributeName, schema, errors, allowedTypes);
    }
    if (
      attributes?.schemaVersion?.type !== "number" ||
      attributes.schemaVersion.default !== identity.schemaVersion
    ) {
      errors.push(`${label} schemaVersion attribute must default to ${identity.schemaVersion}`);
    }
    if (
      attributes?.blockId?.type !== "string" ||
      attributes.blockId.default !== identity.catalogId
    ) {
      errors.push(`${label} blockId attribute must default to ${identity.catalogId}`);
    }
    for (const [legacyName, legacyType] of Object.entries(compatibility?.legacyReads ?? {})) {
      if (legacyName in attributes)
        errors.push(`${label} declares ${legacyName} as canonical and legacy`);
      if (!allowedTypes.has(legacyType))
        errors.push(`${label} legacy read ${legacyName} has an invalid type`);
    }
    const legacyLinks = compatibility?.legacyLinks ?? [];
    if (
      !Array.isArray(legacyLinks) ||
      legacyLinks.some(
        (value) => typeof value !== "string" || !/^[A-Za-z][A-Za-z0-9]*$/.test(value),
      )
    ) {
      errors.push(`${label} legacy links must be attribute key names`);
    }
    if (!renderer.preview.label.trim()) errors.push(`${label} has no preview label`);
    if (!renderer.preview.attributes || Array.isArray(renderer.preview.attributes)) {
      errors.push(`${label} preview attributes must be an object`);
    }
    const rendererPath = join(rendererRoot, renderer.module);
    if (!existsSync(rendererPath))
      errors.push(`${label} renderer does not exist: ${renderer.module}`);
    const editorScript = join(pluginBlocksRoot, identity.catalogId, "index.js");
    if (
      editor.bespoke &&
      (!existsSync(editorScript) || readFileSync(editorScript, "utf8").startsWith(generatedHeader))
    ) {
      errors.push(`${label} bespoke editor does not exist: ${bespokeEditorPath(registration)}`);
    }
    if (editor.keywords !== undefined) {
      if (!Array.isArray(editor.keywords) || editor.keywords.length === 0) {
        errors.push(`${label} declares keywords but not as a non-empty array`);
      } else if (
        editor.keywords.some((keyword) => typeof keyword !== "string" || !keyword.trim())
      ) {
        errors.push(`${label} has a blank inserter keyword`);
      } else if (duplicates(editor.keywords).length > 0) {
        errors.push(`${label} repeats an inserter keyword`);
      }
    }
    if (!existsSync(join(docsRoot, documentation.path))) {
      errors.push(`${label} documentation does not exist: ${documentation.path}`);
    }
  }

  const referencedRenderers = new Set(registrations.map((item) => item.renderer.module));
  const rendererFiles = globSync("*.astro", { cwd: rendererRoot });
  for (const file of rendererFiles) {
    if (file.startsWith("Core") || file === "GravityFormBlock.astro") continue;
    if (!referencedRenderers.has(file)) errors.push(`Unregistered structured renderer: ${file}`);
  }

  const catalogIds = new Set(registrations.map((item) => item.identity.catalogId));
  for (const file of globSync("*/index.js", { cwd: pluginBlocksRoot })) {
    const catalogId = dirname(file);
    if (!catalogIds.has(catalogId))
      errors.push(`Unregistered block directory: blocks/${catalogId}`);
  }

  const excludedDocs = new Set([
    "ARCHITECTURE.md",
    "README.md",
    "WORDPRESS-IMPLEMENTATION.md",
    "WORDPRESS-SMOKE-TEST.md",
  ]);
  const referencedDocs = new Set(registrations.map((item) => item.documentation.path));
  for (const path of globSync("**/*.md", { cwd: docsRoot })) {
    if (excludedDocs.has(path)) continue;
    if (!referencedDocs.has(path)) errors.push(`Unregistered Gutenberg brief: ${path}`);
  }

  if (errors.length > 0) fail(errors);
}

/**
 * Key names whose string values a block's renderer uses as link targets: every
 * `ui.kind: "url"` attribute at any depth, the legacy names it still reads, and
 * the `compatibility.legacyLinks` the schema cannot express (a legacy top-level
 * `ctaUrl`, the `href` inside an untyped `cta` object).
 */
export function linkKeys(registration) {
  const keys = new Set(registration.compatibility?.legacyLinks ?? []);
  const walk = (attributes) => {
    for (const [name, schema] of Object.entries(attributes ?? {})) {
      if (schema?.ui?.kind === "url") {
        keys.add(name);
        for (const legacy of schema.legacyReads ?? []) keys.add(legacy);
      }
      walk(schema?.properties);
      walk(schema?.items?.properties);
    }
  };
  walk(registration.attributes);
  return [...keys].sort();
}

function json(value) {
  return JSON.stringify(value);
}

function typescriptValue(value, indent = 0) {
  const space = " ".repeat(indent);
  const childSpace = " ".repeat(indent + 2);
  if (Array.isArray(value)) {
    if (value.length === 0) return "[]";
    return `[\n${value.map((item) => `${childSpace}${typescriptValue(item, indent + 2)},`).join("\n")}\n${space}]`;
  }
  if (value && typeof value === "object") {
    const entries = Object.entries(value);
    if (entries.length === 0) return "{}";
    return `{\n${entries
      .map(([key, entry]) => {
        const property = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : json(key);
        return `${childSpace}${property}: ${typescriptValue(entry, indent + 2)},`;
      })
      .join("\n")}\n${space}}`;
  }
  return json(value);
}

